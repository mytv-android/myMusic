/*
 * 海报墙放大重排表。版式机制改编自 chthollyphile/folia-major 的 Lattice（AGPL-3.0）：
 * https://github.com/chthollyphile/folia-major
 *
 * 一格放大到 6×6 时，6×6 落在块内 8 个对齐位置之一（x ∈ {0, 2, 4, 6}，y ∈ {0, 2}），其余 60 格用 11 块精确铺满；
 * 在所有铺法里取“其余 11 首按原顺序各就各位时总位移最小”的那种。放大格不一定盖住它原来的位置，
 * 只要整块挪得最少。4 模板 × 4 镜像 × 12 位 = 192 种情况由原型离线算好（每种 300 万节点上限，实际都没碰到），
 * 这里原样照抄：键是“模板.镜像.位”，值是按位顺序排开的 12 个矩形 (x, y, w, h)，每个数一位 13 进制，共 48 位。
 * [WallReflowTable.solve] 是同一段分支定界求解器，用于单测核对表，以及表里万一缺了时现算。
 */
package com.mytv.mymusic.ui.poster

import com.mytv.mymusic.ui.poster.WallLayout.BLOCK_H
import com.mytv.mymusic.ui.poster.WallLayout.BLOCK_W
import com.mytv.mymusic.ui.poster.WallLayout.GROW
import com.mytv.mymusic.ui.poster.WallLayout.SLOTS
import kotlin.math.abs
import kotlin.math.max
import kotlin.math.sqrt

internal object WallReflowTable {
    /** 模板 × 镜像 × 位。 */
    const val CASES = 4 * 4 * SLOTS

    /** 原型运行时求解的节点上限；离线生成表用的是 300 万，两者结果相同。 */
    const val DEFAULT_NODE_BUDGET = 400_000

    private const val RADIX = 13

    /** 放大卡可以落的左上角。 */
    private val GROWN_X = intArrayOf(0, 2, 4, 6)
    private val GROWN_Y = intArrayOf(0, 2)

    fun key(template: Int, mirror: Int, slot: Int): String = "$template.$mirror.$slot"

    val keys: Set<String> get() = PACKED.keys

    fun packed(template: Int, mirror: Int, slot: Int): String? = PACKED[key(template, mirror, slot)]

    /** 放大第 [slot] 位后整块的 12 个位，下标和原来的位一一对应，第 [slot] 个是 6×6。 */
    fun rects(template: Int, mirror: Int, slot: Int): List<UnitRect> = DECODED[(template * 4 + mirror) * SLOTS + slot]

    private val DECODED: List<List<UnitRect>> by lazy {
        List(CASES) { i ->
            val t = i / (4 * SLOTS)
            val m = i / SLOTS % 4
            val s = i % SLOTS
            packed(t, m, s)?.let(::decode) ?: solve(t, m, s)
        }
    }

    fun decode(packed: String): List<UnitRect> {
        require(packed.length == SLOTS * 4) { "重排串应为 ${SLOTS * 4} 位：$packed" }
        val v = IntArray(packed.length) { packed[it].digitToInt(RADIX) }
        return List(SLOTS) { i -> UnitRect(v[i * 4], v[i * 4 + 1], v[i * 4 + 2], v[i * 4 + 3]) }
    }

    fun encode(rects: List<UnitRect>): String = buildString {
        for (r in rects) for (v in intArrayOf(r.x, r.y, r.w, r.h)) append(v.toString(RADIX))
    }

    /**
     * 现算一种重排：6×6 依次试 8 个位置（放置代价 = 与原中心的距离 × 2.2），其余 60 格深度优先铺满。
     * 每次总是填最靠前的空格，所以放下的顺序就是阅读顺序，第 k 块直接对应其余歌里的第 k 首；
     * 每块的代价 = 中心位移 + 面积差 × 0.35，边放边累计，超过当前最优就剪掉。
     * 距离用与 V8 Math.hypot 逐位一致的算法，平局的取舍和原型完全相同。
     */
    fun solve(template: Int, mirror: Int, slot: Int, nodeBudget: Int = DEFAULT_NODE_BUDGET): List<UnitRect> {
        val base = WallLayout.slotRects(template, mirror)
        val g = base[slot]
        val gcx = g.x + g.w / 2.0
        val gcy = g.y + g.h / 2.0
        val solver = ReflowSolver(base.filterIndexed { i, _ -> i != slot }, nodeBudget)
        for (px in GROWN_X) for (py in GROWN_Y) {
            val placeCost = jsHypot(px + GROW / 2.0 - gcx, py + GROW / 2.0 - gcy) * 2.2
            if (placeCost >= solver.bestCost) continue
            solver.search(px, py, placeCost)
        }
        val rest = checkNotNull(solver.best) { "重排无解：${key(template, mirror, slot)}" }
        var j = 0
        return List(SLOTS) { i -> if (i == slot) UnitRect(solver.bestX, solver.bestY, GROW, GROW) else rest[j++] }
    }

    private class ReflowSolver(private val others: List<UnitRect>, private val budget: Int) {
        private val cells = BooleanArray(BLOCK_W * BLOCK_H)
        private val placed = IntArray((SLOTS - 1) * 4)
        private var nodes = 0
        private var px = 0
        private var py = 0

        var bestCost = Double.POSITIVE_INFINITY
            private set
        var best: List<UnitRect>? = null
            private set
        var bestX = 0
            private set
        var bestY = 0
            private set

        fun search(px: Int, py: Int, placeCost: Double) {
            cells.fill(false)
            mark(px, py, GROW, GROW, true)
            this.px = px
            this.py = py
            nodes = budget
            dfs(0, BLOCK_W * BLOCK_H - GROW * GROW, placeCost)
        }

        private fun dfs(k: Int, free: Int, cost: Double) {
            if (--nodes <= 0) return
            if (k == SLOTS - 1) {
                if (free == 0 && cost < bestCost) {
                    bestCost = cost
                    best = List(SLOTS - 1) { UnitRect(placed[it * 4], placed[it * 4 + 1], placed[it * 4 + 2], placed[it * 4 + 3]) }
                    bestX = px
                    bestY = py
                }
                return
            }
            val left = SLOTS - 1 - k
            if (free < left * 4 || free > left * 24) return
            var i = 0
            while (cells[i]) i++
            val x0 = i % BLOCK_W
            val y0 = i / BLOCK_W
            val a = others[k]
            for ((w, h) in WallLayout.SIZES) {
                if (x0 + w > BLOCK_W || y0 + h > BLOCK_H) continue
                val c = cost + jsHypot(a.x + a.w / 2.0 - x0 - w / 2.0, a.y + a.h / 2.0 - y0 - h / 2.0) +
                    abs(a.w * a.h - w * h) * 0.35
                if (c >= bestCost) continue
                if (!fits(x0, y0, w, h)) continue
                mark(x0, y0, w, h, true)
                placed[k * 4] = x0
                placed[k * 4 + 1] = y0
                placed[k * 4 + 2] = w
                placed[k * 4 + 3] = h
                dfs(k + 1, free - w * h, c)
                mark(x0, y0, w, h, false)
            }
        }

        private fun fits(x0: Int, y0: Int, w: Int, h: Int): Boolean {
            for (y in y0 until y0 + h) for (x in x0 until x0 + w) if (cells[y * BLOCK_W + x]) return false
            return true
        }

        private fun mark(x0: Int, y0: Int, w: Int, h: Int, on: Boolean) {
            for (y in y0 until y0 + h) for (x in x0 until x0 + w) cells[y * BLOCK_W + x] = on
        }
    }

    /** V8 的 Math.hypot：按最大值归一化后做 Kahan 求和再开方，结果与原型逐位一致（JVM 的 hypot 可能差一个 ulp）。 */
    private fun jsHypot(a: Double, b: Double): Double {
        val x = abs(a)
        val y = abs(b)
        val m = max(x, y)
        if (m == 0.0) return 0.0
        // 只有两个参数时 Kahan 的补偿项恒为 0，化简后就是这一行
        val nx = x / m
        val ny = y / m
        return sqrt(nx * nx + ny * ny) * m
    }

